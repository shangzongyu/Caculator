#include "AddStrategy.h"

/*******************************************************************************
 * 函数名称： getResult
 * 功能描述： 获得结果
 * 参数列表：
 *  leftOperand  - 左操作数
 *  rightOperand - 右操作数
 *
 * 返回结果： 结果
 ******************************************************************************/
double AddStrategy::getResult(double leftOperand, double rightOperand) const
{
    return leftOperand + rightOperand;
}
